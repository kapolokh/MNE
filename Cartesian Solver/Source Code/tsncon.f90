        w(1)=0.07332178d+0
        w(2)=0.05266740d+0
        w(3)=0.04161495d+0
        w(4)=w(3)
        w(5)=w(2)
        w(6)=w(1)
        w(7)=w(2)
        w(8)=0.03895667d+0
        w(9)=0.03249018d+0
        w(10)=w(8)
        w(11)=w(2)
        w(12)=w(3)
        w(13)=w(9)
        w(14)=w(9)
        w(15)=w(3)
        w(16)=w(3)
        w(17)=w(8)
        w(18)=w(3)
        w(19)=w(2)
        w(20)=w(2)
        w(21)=w(1)
      elseif (n.eq.14) then
        u(1)=0.14238965d+0
        u(2)=0.42048076d+0
        u(3)=0.57735027d+0
        u(4)=0.69990185d+0
        u(5)=0.80398498d+0
        u(6)=0.89605866d+0
        u(7)=0.97951538d+0
        w(1)=0.062171628d+0
        w(2)=0.043325697d+0
