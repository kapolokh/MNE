        w(10)=w(3)
        w(11)=w(7)
        w(12)=w(3)
        w(13)=w(2)
        w(14)=w(2)
        w(15)=w(1)
      elseif (n.eq.12) then
        u(1)=0.15395746d+0
        u(2)=0.45769112d+0
