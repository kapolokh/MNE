        w(5)=w(2)
        w(6)=w(1)
      elseif (n.eq.8) then
        u(1)=0.19232747d+0
        u(2)=0.57735027d+0
        u(3)=0.79352178d+0
        u(4)=0.96229948d+0
        w(1)=0.11678847d+0
        w(2)=0.09325523d+0
        w(3)=w(2)
