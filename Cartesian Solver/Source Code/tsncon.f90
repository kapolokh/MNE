      i=n/2

      if (n.eq.2) then
        w(1)=1.0d0
        u(1)=1.0d0/sqrt(3.0d0)    ! .57735027d+0
        e(1)=u(1)
        go to 240
      elseif (n.eq.4) then
        u(2)=0.90444905d+0
        u(1)=0.30163878d+0
        w(1)=0.33333333d+0
        w(2)=w(1)
        w(3)=w(1)
      elseif (n.eq.6) then
        u(1)=0.23009194d+0
        u(2)=0.68813432d+0
        u(3)=0.94557676d+0
        w(1)=0.16944656d+0
        w(2)=0.16388677d+0
        w(3)=w(1)
