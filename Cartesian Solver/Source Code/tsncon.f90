!     reorder sn library
!
      k=1
      l=mm
  260 t=u(k)
      u(k)=u(l)
      u(l)=t
      t=e(k)
      e(k)=e(l)
      e(l)=t
      t=w(k)
      w(k)=w(l)
      w(l)=t
      k=k+1
      l=l-1
      if (k.lt.l) go to 260
!
      return
      end subroutine tsncon